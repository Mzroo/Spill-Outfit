<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Factories\HasFactory;

class Pesanan extends Model
{
    use HasFactory;

    protected $table = 'pesanan';

    protected $fillable = [

        /*
        |--------------------------------------------------------------------------
        | USER
        |--------------------------------------------------------------------------
        */
        'user_id',

        'kode_pesanan',

        /*
        |--------------------------------------------------------------------------
        | PENERIMA
        |--------------------------------------------------------------------------
        */
        'nama_penerima',

        'no_hp',

        'provinsi',

        'kota',

        'alamat',

        'kode_pos',

        'catatan',

        /*
        |--------------------------------------------------------------------------
        | RAJA ONGKIR
        |--------------------------------------------------------------------------
        */
        'destination_id',

        'courier',

        /*
        |--------------------------------------------------------------------------
        | TOTAL
        |--------------------------------------------------------------------------
        */
        'subtotal',

        'ongkir',

        'total_harga',

        /*
        |--------------------------------------------------------------------------
        | PEMBAYARAN
        |--------------------------------------------------------------------------
        */
        'metode_pembayaran',

        /*
        |--------------------------------------------------------------------------
        | MIDTRANS
        |--------------------------------------------------------------------------
        */
        'midtrans_order_id',

        'snap_token',

        'transaction_id',

        /*
        |--------------------------------------------------------------------------
        | STATUS
        |--------------------------------------------------------------------------
        */
        'status',

    ];

    /*
    |--------------------------------------------------------------------------
    | RELASI USER
    |--------------------------------------------------------------------------
    */
    public function user()
    {
        return $this->belongsTo(User::class);
    }

    /*
    |--------------------------------------------------------------------------
    | RELASI ITEM PESANAN
    |--------------------------------------------------------------------------
    */
    public function items()
    {
        return $this->hasMany(
            PesananItem::class,
            'pesanan_id'
        );
    }
}